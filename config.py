# ===== Role 2: 一次スクリーニング条件 =====

# 時価総額の上限（円）※3倍の余地を残すため
MAX_MARKET_CAP = 50_000_000_000        # 500億円

# 時価総額の下限（円）※小さすぎると流動性が死ぬ
MIN_MARKET_CAP = 3_000_000_000         # 30億円

# 1日の売買代金の下限（円）※自分が降りられる最低ライン
MIN_TURNOVER_VALUE = 300_000_000       # 3億円

# 直近四半期の営業利益 前年同期比（★主軸指標）
MIN_OP_PROFIT_YOY = 0.30               # +30%以上

# 直近四半期の売上高 前年同期比（コスト削減だけの増益を除外）
MIN_SALES_YOY = 0.15                   # +15%以上

# 株価の下限（円）
MIN_PRICE = 200

# 株価の上限（円）※Noneなら上限なし。低位株に絞りたいとき使う
MAX_PRICE = None

# 赤字→黒字転換も通過させるか
ALLOW_TURNAROUND = True

# 対象market（Noneなら全市場）
# 例: ["プライム", "スタンダード", "グロース"]
TARGET_MARKETS = None

# 除外したい業種（33業種名の部分一致）
EXCLUDE_SECTORS = ["銀行業", "保険業", "証券、商品先物取引業"]


# ===== 補助指標 =====

# 売買代金が20日平均の何倍以上か（0にすると無効）
MIN_TURNOVER_SPIKE_RATIO = 0.0         # 3か月版では主軸ではないので初期値0

# 出来高の移動平均を取る日数
MA_WINDOW = 20


# ===== データ取得 =====

# 何営業日分の株価を取得するか（移動平均の計算に必要）
PRICE_LOOKBACK_DAYS = 60

# 決算サマリーを何日さかのぼって取得するか（前年同期比の計算に必要）
FIN_LOOKBACK_DAYS = 500

# EDINET: 大量保有報告書を何日分チェックするか
EDINET_LOOKBACK_DAYS = 30

# 出力先ディレクトリ
OUTPUT_DIR = "output"

# ===== バックテスト =====

# 何日分さかのぼるか（Freeプランの上限は約2年）
BACKTEST_LOOKBACK_DAYS = 730

# 何営業日ごとにスクリーニングを実行するか（21 ≒ 1か月）
BACKTEST_STEP_DAYS = 21


# ===== メール配信 =====

# True にすると、候補が0件の日は日次メールを送りません。
# 「見るべき銘柄が出たときだけ知らせる」運用向け。
# 週次メールは候補の有無にかかわらず必ず届くので、
# それが止まればシステムの異常に気づけます。
DAILY_MAIL_ONLY_WHEN_HITS = True

# ===== 検証チェック =====

# 週次で何銘柄まで詳細チェックにかけるか
MAX_DETAIL_CHECK = 10

# LLMは使用しません。すべての判定はAPIの数値と計算結果のみに基づきます。
# 「不明」の項目は不合格として扱われ、その銘柄は通過しません。


# ===== データ遅延 =====

# プランごとのデータ遅延日数。
#   Free     : 90（12週間遅延。余裕を持たせて90）
#   Light以上: 0
# 今日の日付でリクエストすると契約範囲外エラー(400)になるため、
# この日数だけ手前を終端にしてリクエストします。
DATA_LAG_DAYS = 0


# ===== APIレート制限 =====

# 1分あたりのリクエスト上限。プランに合わせて変更してください。
#   Free     : 5
#   Light以上: 60
# 超過すると429エラーになり、大幅に超えると5分程度アクセスが遮断されます。
RATE_LIMIT_PER_MIN = 60

# 429が出たときの待機秒数（線形に増やして再試行）
RETRY_WAIT_SEC = 60
RETRY_MAX = 3
